"""Regenerate the preset fixtures tests/unit/test_presets_linked.c links.

Each fixture is what a presets-only build links, made by the openlifu SDK's
own generators from a preset context in openlifu-diathermy-application
(preset_settings/<context>/presets.json lists the presets in index order):

    one preset   presets/fda_preset.h            generate_fda_preset
    several      presets/preset_table.h + one    generate_preset_set
                 header per preset

expected.h holds what the host computes for each index, independently of the
firmware: the preset id, settings_crc, regs_crc and run lengths.

    python tests/unit/fixtures/generate.py <preset_settings dir> fda test
"""

import json
import sys
from pathlib import Path

from openlifu_sdk.io.LIFUTXPresets import (
    compile_preset,
    generate_fda_preset,
    generate_preset_set,
    regs_crc,
)

HERE = Path(__file__).resolve().parent


def load_context(context: Path) -> list:
    ids = json.loads((context / "presets.json").read_text(encoding="utf-8"))["presets"]
    configs = []
    for preset_id in ids:
        raw = (context / preset_id / ("%s_settings.json" % preset_id)).read_bytes()
        configs.append(compile_preset(json.loads(raw), preset_id=preset_id, settings_bytes=raw))
    return configs


def write_expected(path: Path, context: str, configs: list) -> None:
    lines = [
        "// Generated by tests/unit/fixtures/generate.py from the '%s' preset context." % context,
        "// What the host computes for each preset index (openlifu SDK compile_preset).",
        "#ifndef FIXTURE_EXPECTED_H_",
        "#define FIXTURE_EXPECTED_H_",
        "",
        "#include <stdint.h>",
        "",
        "#define EXPECTED_COUNT %uu" % len(configs),
        "",
        "static const struct {",
        "\tconst char *id;",
        "\tuint32_t settings_crc;",
        "\tuint32_t regs_crc;",
        "\tuint8_t train_count_len;",
        "\tuint32_t train_counts[16];",
        "} expected[EXPECTED_COUNT] = {",
    ]
    for mc in configs:
        counts = [int(c) for c in mc["pulse_train_count_selections"]]
        lines.append('\t{ "%s", 0x%08xu, 0x%08xu, %uu, { %s } },'
                     % (mc["id"], mc["settings_crc"], regs_crc(mc, 0), len(counts),
                        ", ".join("%uu" % c for c in counts)))
    lines += ["};", "", "#endif  // FIXTURE_EXPECTED_H_", ""]
    path.write_text("\n".join(lines), encoding="utf-8")


def main(argv: list) -> int:
    settings = Path(argv[1])
    for context in argv[2:]:
        configs = load_context(settings / context)
        out = HERE / context
        presets = out / "presets"
        presets.mkdir(parents=True, exist_ok=True)
        for old in presets.glob("*.h"):
            old.unlink()
        if len(configs) == 1:
            generate_fda_preset(presets, configs[0], context)
        else:
            generate_preset_set(presets, configs, context)
        write_expected(out / "expected.h", context, configs)
        print("%s: %d preset(s) -> %s" % (context, len(configs), out))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
