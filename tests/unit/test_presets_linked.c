static int failures = 0;
static unsigned loads = 0;

#define CHECK(cond, ...)                                            \
	do {                                                            \
		if (!(cond)) {                                              \
			failures++;                                             \
			printf("FAIL %s:%d: ", __FILE__, __LINE__);             \
			printf(__VA_ARGS__);                                    \
			printf("\n");                                           \
		}                                                           \
	} while (0)

