/*
 * Host-side test of the presets a presets-only (FDA_MODE) image links in
 * (Core/Src/presets.c): one preset from fda_preset.h, or a set from
 * preset_table.h (PRESET_TABLE).
 *
 * Built by tests/unit/run.sh once per fixture in tests/unit/fixtures/: the
 * SDK's own headers for a preset context, and expected.h, what the host
 * computes for each index. Checks that index i is the host's preset i, that
 * loading it needs that preset's own CRCs, and that every index past the set
 * is refused.
 */

